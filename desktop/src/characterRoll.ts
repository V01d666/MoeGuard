function pick<T>(values:readonly T[], random:()=>number):T {
  return values[Math.floor(random()*values.length)];
}

export function rollCharacter(previous:{kind:string;name:string}, random:()=>number = Math.random) {
  const [kind,outfits,accessories]=pick(themes.filter(theme=>theme[0]!==previous.kind),random);
  return {kind,style:pick(styles,random),hair:pick(hair,random),eyes:pick(eyes,random),
    outfit:pick(outfits,random),accessory:pick(accessories,random),
    name:pick(names.filter(name=>name!==previous.name.trim()),random)};
}
